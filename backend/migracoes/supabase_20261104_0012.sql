-- Cesta do Vale: confirmação de e-mail e recuperação de senha.
-- Cole no Supabase Dashboard > SQL Editor. O script preserva as contas existentes.
-- Contas existentes ficam email_verificado=false e precisarão confirmar o endereço.

ALTER TABLE public.usuarios
  ADD COLUMN IF NOT EXISTS email_verificado boolean NOT NULL DEFAULT false;

ALTER TABLE public.usuarios
  ADD COLUMN IF NOT EXISTS versao_sessao integer NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS public.tokens_conta (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id),
  tipo varchar(24) NOT NULL,
  token_hash varchar(64) NOT NULL UNIQUE,
  criado_em timestamp without time zone NOT NULL,
  expira_em timestamp without time zone NOT NULL,
  usado_em timestamp without time zone
);

CREATE INDEX IF NOT EXISTS ix_tokens_conta_usuario_id
  ON public.tokens_conta (usuario_id);

CREATE INDEX IF NOT EXISTS ix_tokens_conta_expira_em
  ON public.tokens_conta (expira_em);

-- Bloqueia leitura/escrita pela API pública do Supabase. Sem políticas,
-- somente a conexão administrativa do backend pode acessar esta tabela.
ALTER TABLE public.tokens_conta ENABLE ROW LEVEL SECURITY;
