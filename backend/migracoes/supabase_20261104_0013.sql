ALTER TABLE public.cestas
  ADD COLUMN IF NOT EXISTS enviado_em timestamp with time zone;

CREATE TABLE IF NOT EXISTS public.notificacoes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  cesta_id integer NOT NULL REFERENCES public.cestas(id) ON DELETE CASCADE,
  titulo varchar(120) NOT NULL,
  mensagem text NOT NULL,
  criada_em timestamp with time zone NOT NULL,
  lida boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS ix_notificacoes_usuario_id
  ON public.notificacoes (usuario_id);

ALTER TABLE public.notificacoes ENABLE ROW LEVEL SECURITY;
